"""Shared helpers for the ClearView training pipeline."""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import yaml

CATEGORIES = ("ad", "safety", "ignore")
IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


@dataclass(frozen=True)
class ClassDef:
    name: str
    category: str


def load_config(path: str | Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    validate_config(cfg)
    return cfg


def validate_config(cfg: dict) -> None:
    classes = cfg.get("classes")
    if not classes:
        raise ValueError("config must define a non-empty 'classes' list")
    seen = set()
    for c in classes:
        if c.get("category") not in CATEGORIES:
            raise ValueError(f"class {c.get('name')!r}: category must be one of {CATEGORIES}")
        if c["name"] in seen:
            raise ValueError(f"duplicate class name {c['name']!r}")
        seen.add(c["name"])
    if not any(c["category"] == "safety" for c in classes):
        raise ValueError("at least one 'safety' class is required: ClearView must know what never to cover")
    for src in cfg.get("sources", []):
        for target in (src.get("map") or {}).values():
            if target is not None and target not in seen:
                raise ValueError(f"source {src.get('name')!r} maps to unknown class {target!r}")


def class_defs(cfg: dict) -> list[ClassDef]:
    return [ClassDef(c["name"], c["category"]) for c in cfg["classes"]]


def unity_labels_text(classes: list[ClassDef]) -> str:
    lines = ["# index,name,category  (generated by ClearView ml pipeline)"]
    lines += [f"{i},{c.name},{c.category}" for i, c in enumerate(classes)]
    return "\n".join(lines) + "\n"


def read_source_names(src: dict, root: Path) -> list[str]:
    """Class names of a YOLO-format source, from the config or from its data.yaml."""
    if "names" in src:
        return list(src["names"])
    data_yaml = root / src["path"] / "data.yaml"
    if not data_yaml.exists():
        raise FileNotFoundError(f"source {src['name']!r}: give 'names' or provide {data_yaml}")
    with open(data_yaml, "r", encoding="utf-8") as f:
        names = yaml.safe_load(f)["names"]
    if isinstance(names, dict):
        return [names[k] for k in sorted(names, key=int)]
    return list(names)
